<?php

namespace App\Enums;

/**
 * Насколько глубоко забираем отзывы.
 *
 * Яндекс отдаёт максимум около 600 отзывов на одну выдачу — дальше бэкенд отвечает ошибкой,
 * и это ограничение самого источника, одинаковое и для сайта, и для браузера пользователя.
 * Обойти его нельзя, но можно запросить выдачу в другом порядке: срезы «сначала худшие» и
 * «сначала лучшие» не пересекаются вовсе, поэтому объединение нескольких проходов покрывает
 * заметно больше, чем один.
 */
enum FetchMode: string
{
    case Recent = 'recent';
    case Maximum = 'maximum';

    public function label(): string
    {
        return match ($this) {
            self::Recent => 'Только свежие (до 600)',
            self::Maximum => 'Максимум (несколько проходов)',
        };
    }

    public function description(): string
    {
        return match ($this) {
            self::Recent => 'Один проход по свежим отзывам. Быстро, хватает для наблюдения за новыми.',
            self::Maximum => 'Несколько проходов с разной сортировкой. Дольше, но собирает заметно больше.',
        };
    }

    /**
     * Порядки сортировки, которые эндпоинт принимает. Для максимального режима они идут
     * подряд: сначала два непересекающихся края по оценке, затем остальные — добирать середину.
     *
     * @return string[]
     */
    public function rankings(): array
    {
        return match ($this) {
            self::Recent => ['by_time'],
            self::Maximum => [
                'by_rating_desc',
                'by_rating_asc',
                'by_time',
                'by_relevance_org',
                'by_aspect_tone_desc',
                'by_aspect_tone_asc',
            ],
        };
    }
}
