<?php

namespace App\Services\YandexMaps\Exceptions;

/**
 * Ответ пришёл, но выглядит не так, как мы ожидаем: пропало поле, поменялась вложенность,
 * вместо JSON прилетел HTML.
 *
 * Это тот случай, ради которого исключение и заведено: молча вернуть ноль отзывов и
 * записать в базу пустоту — значит превратить сломанный парсер в «успешный» результат.
 */
class SourceChanged extends ParsingFailed
{
    public function userMessage(): string
    {
        return 'Яндекс изменил формат данных — парсер требует обновления. Мы уже знаем об этом.';
    }
}
