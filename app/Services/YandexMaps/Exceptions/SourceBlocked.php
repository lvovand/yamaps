<?php

namespace App\Services\YandexMaps\Exceptions;

/**
 * Яндекс перестал отвечать по-хорошему: капча, 403 или 429.
 *
 * Повторять запрос в этот момент — худшее, что можно сделать: так адрес блокируют
 * основательно и надолго. Задача останавливается, а повтор остаётся за человеком.
 */
class SourceBlocked extends ParsingFailed
{
    public function userMessage(): string
    {
        return 'Яндекс временно ограничил доступ к данным. Попробуйте запустить обновление позже.';
    }
}
